/**
 * 内置角色「大肥鱼」的**三种**皮肤。
 *
 * ## 内容来源（2.34，2026-11-01）
 *
 * 六块文本**逐字**来自 `whalechat/docs/大肥鱼-五皮肤人设.md`（该文档是历史存档，
 * 里面还留着后来删除的「小女儿」「MC老登」原文），那份文档又是从 AstrBot 人格卡
 * （`大肥鱼.docx` / `魔丸大肥鱼.docx` / `贴吧老哥大肥鱼.docx`）**只换平台、不改性格**改造来的。
 *
 * ## 2.38 删「小女儿」、2.381 删「MC老登」（用户 2026-11-01 拍板）
 *
 * 原来的「小女儿」（「爸爸」称呼 + 成人向调侃）与「MC老登」（MC 技术宅）**已整份删除**：
 *  * 枚举里没有 `DAUGHTER` / `MC`，[ALL] 只剩三份 ⇒ 选择页、换皮肤、主动消息文案都不会再出现；
 *  * 已经选过它们的老设备由 `ChatEngine.seedBuiltinPersonasIfNeeded()` 里的一次性强覆盖
 *    换回基础款（标记位 `fish_daughter_removed_38` / `fish_mc_removed_381`），
 *    **不留下任何那份人设文本**；
 *  * `FishSkinKey.fromPrefs("daughter" / "mc")` 现在返回 null ⇒ 读盘兜底成 [DEFAULT]。
 *
 * **不要把这两份文本加回来。** 不是「暂时下架」，是产品决定删除；
 * 要从历史文档里翻回来，先让用户重新拍板。
 *
 * ## ⚠️ 改剩下的文本之前先读这段
 *
 * **不许润色、不许「优化」、不许把脏话洗掉。** 这三份是用户拍板的人设定稿，
 * 写进产品的是它的「人味」，而人味恰恰来自那些看起来不规整的地方
 * （「?现在知道错了」「行吧 算你有点东西」）。
 * 真觉得某句要改，那是一次**用户拍板**的事，不是实现者顺手改的。
 *
 * 另外两件事也不能动：
 *  * **三个皮肤共用 [BuiltinPersonas.BUILTIN_FISH_ID]。** 换皮肤 = 原地改那条
 *    persona 的字段，不是新建角色。理由见 [BuiltinPersonas] 的注释（按 id 去重）。
 *  * **示例对话的说话人视角**：`你：` = 用户、`大肥鱼：` = 她。这是项目约定，
 *    三份皮肤都照抄成了「大肥鱼：」（源文件就是这么写的）。
 *
 * ## 为什么不在这里拼输出规矩
 *
 * [CHAT_OUTPUT_RULES] 仍然由 `ChatEngine` 在运行时追加，三份人设都受它约束。
 * 人设自己写的「短」是**风格**，规矩里的「短」是**底线**，两者不冲突。
 */
enum class FishSkinKey {
    BASE,
    MOWAN,
    TIEBA,
    ;

    /** 落盘用的值：`base` / `mowan` / `tieba`。 */
    val prefsValue: String get() = name.lowercase()

    companion object {
        /** 认不出来的值返回 null，**不要**兜底成 BASE —— 调用方才知道该不该兜。 */
        fun fromPrefs(value: String?): FishSkinKey? {
            val target = value?.trim()?.lowercase() ?: return null
            return entries.firstOrNull { it.prefsValue == target }
        }
    }
}

/**
 * 一个皮肤。
 *
 * 字段和 [Persona] 的六块一一对应（[greeting] 是第六块，不进 system prompt，
 * 只作为第一条消息上架），外加卡片上的 [name] / [tagline]。
 *
 * [name] ≤ [PERSONA_NAME_MAX]（6）、[tagline] ≤ [PERSONA_TAGLINE_MAX]（12）——
 * 这是通讯录卡片标题位 / 副标题位的宽度，超了会被截断。五份皮肤都在这两条线内，
 * 但改文案时仍然要自己核一遍（没有运行时断言：文案写错应该在评审时看出来，
 * 而不是让 App 启动即崩）。
 */
data class FishSkin(
    val key: FishSkinKey,
    /** 通讯录卡片上显示的名字，≤6 字。**跟着皮肤变**。 */
    val name: String,
    /** 通讯录卡片副标题，≤12 字。 */
    val tagline: String,

    // ------------------------------------------------------------ 人设六块
    /** ① 人格内核 */
    val soul: String,
    /** ② 说话风格 */
    val style: String,
    /** ③ 行为规则 */
    val rules: String,
    /** ④ 场景 */
    val scenario: String,
    /** ⑤ 示例对话 */
    val examples: String,
    /** ⑥ 开场白 */
    val greeting: String,
) {
    /**
     * 选择页上展示的开场白**第一句**。
     *
     * 用第一句而不是整段：五份开场白都是两行、都是一句「在场声明」加一句催问，
     * 卡片上放第一句就够让人闻出味道，放两句会把卡片撑高、五张卡就得滚很久。
     */
    val openingLine: String
        get() = greeting.lineSequence().firstOrNull { it.isNotBlank() }.orEmpty()
}

