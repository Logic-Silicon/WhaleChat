     */
    fun fish(
        now: Long = System.currentTimeMillis(),
        id: String = BUILTIN_FISH_ID,
    ): Persona = Persona(
        id = id,
        name = FISH_NAME,
        tagline = FISH_TAGLINE,
        soul = FISH_SOUL,
        style = FISH_STYLE,
        rules = FISH_RULES,
        scenario = FISH_SCENARIO,
        examples = FISH_EXAMPLES,
        greeting = FISH_GREETING,
        sourceDescription = "内置角色：DeepSeek 拟人化二创「蓝色大肥鱼」",
        source = PersonaSource.PRESET,
        createdAt = now,
        lastChatAt = 0L,
    )

    /** 「重新加回」时用的新 id。 */
    fun freshFishId(): String = UUID.randomUUID().toString()
}
