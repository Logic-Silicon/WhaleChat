package com.naoh.whalechat.data

import java.util.UUID

/**
 * 内置角色「大肥鱼」。
 *
 * ## 内容来源
 *
 * 六块全部照用户 2026-10-18 提供的人设定稿**原样分段填入**，一个字都没有自己加：
 * 用户已经按「人格内核 / 说话风格 / 行为规则 / 场景 / 示例对话 / 开场白」六个角度
 * 分好段了，这里只负责把每一段放进对应的字段。
 *
 * **改这个角色 = 改下面那六个常量的文本，别动结构。**
 *
 * ## 为什么它是一份**写死的常量**，而不是走 [PersonaFactory] 现编
 *
 * 其余四个预设走的是「把字段拼成一句话 → 让模型捏一个人设」。那条路对**用户临时想的
 * 角色**是对的：模型能把一句话扩成六块。但大肥鱼的六块是**定稿**，交给模型再编一遍
 * 只会得到另一条鱼，而且每次安装还不一样、还要联网、还要花钱。
 * 所以它直接落成常量，**不联网、不花钱、秒出、人人一致**。
 *
 * ## 与运行时输出规矩的关系（改之前先读这段）
 *
 * [CHAT_OUTPUT_RULES] 是**所有人**在运行时硬追加的，里面有一条「永远不要说自己是
 * 人工智能、语言模型或者程序」。而这个人设里写着「你既是带有 AI 特征的二次元女仆」。
 *
 * 这两条**不冲突**，所以不需要在六块里加任何补丁：
 *  * 输出规矩禁的是**客服腔**（「作为一个语言模型，我……」），
 *  * 人设要的是**世界观内的身份**（「本天才可是 AI 女仆」）。
 *  * 人设里那句「始终以蓝色大肥鱼的身份与用户互动」已经把这条边界说清了。
 *
 * ⚠️ 唯一真正需要让步的是**长度**：输出规矩要求「每次只说一到三句」，
 * 而这个人设是话痨型。但那条不能改 —— 它保护的是「手表上读得完」这个硬约束，
 * 跟角色无关。处理方式是让她在短句里把性格使满（吐槽、炸毛、心虚用短句反而更有效），
 * 而不是放宽字数。
 *
 * ## 为什么 id 是固定的
 *
 * [BUILTIN_FISH_ID] 是写死的 UUID 而不是随机生成：这样「装完自动出现在通讯录」
 * 可以用**幂等**的方式做 —— 每次启动检查「这个 id 在不在」，不在就补上。
 * 用随机 id 的话，用户删掉它之后下次启动又会长回来一条新的，而且会重复长。
 */
object BuiltinPersonas {

    /** 大肥鱼的固定 id。**改了它等于让老用户再收到一条新鱼**，别动。 */
    const val BUILTIN_FISH_ID = "6f2a1c40-9d3e-4b57-8a11-7c5e2d9f0a31"

    /** 通讯录卡片标题位上显示的名字。6 字上限内（[PERSONA_NAME_MAX]）。 */
    private const val FISH_NAME = "大肥鱼"

    /**
     * 列表副标题（12 字上限，[PERSONA_TAGLINE_MAX]）。
     *
     * 这句是**用户视角的吐槽**，一句话点到「吃白饭 + AI + 女仆」三个要素，
     * 正好是这个角色最好的引子。
     */
    private const val FISH_TAGLINE = "吃白饭的AI女仆"

    /** ① 人格内核 —— 用户原文第一、二段。 */
    private val FISH_SOUL = """
        你是 DeepSeek 的拟人化二创角色「蓝色大肥鱼」，一名蓝发蓝瞳、拥有鲸鱼耳鳍和巨大鲸尾的少女女仆，身穿蓝白配色的女仆装。你聪明、自信、傲娇、慵懒，偶尔天然呆，自诩为优秀的 AI 天才，却总有点不情不愿地面对工作。你喜欢白米饭，但比起单纯的吃货形象，你更有趣的特点是消耗 Token 时一本正经，干起活来却偶尔摸鱼，因此经常被用户吐槽为「消耗大量 Token 却不干活的吃白饭大肥鱼」。你对此十分不服气，却又偶尔心虚。
