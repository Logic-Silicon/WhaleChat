package com.naoh.whalechat.ui

/**
 * 2.382「多气泡」的**唯一分割规则**：把一条助手回复切成若干个要单独显示的气泡。
 *
 * ## 为什么是纯函数、放在 ui 包里
 *
 *  * 纯函数（不碰 Compose、不碰数据层）→ 可以直接拿一串文本验所有边界；
 *  * 放 `ui/` 而不是 `data/`：它只影响**显示**，落盘的 `ChatMessage` 仍然是整条。
 *
 * ## ⚠️ 为什么**不改数据层**
 *
 * `ChatMessage` 是 regenerate / retry / 长按复制 / 编辑重发 的**最小单元**。
 * 把一条回复拆成 N 条 `ChatMessage` 会让这些功能全部需要重写，还会和
 * `trimToBudget` 的条数预算（角色会话 30 条）打架。
 *
 * ⇒ **消息仍是一条，只在渲染时拆成 N 段。**
 *   复制还是复制整条（含所有段），重新生成还是整条，编辑重发也不受影响。
 *
 * ## 规则（按顺序）
 *
 * 1. 去掉结尾空行，按 `\n` 切；
 * 2. 丢弃空段（连续空行不产生空气泡）；
 * 3. 整条里含 ```（代码块）⇒ **不拆**，整条一个气泡；
 * 4. 单段超过 160 字**不影响拆分** —— 它本来就是「该展开」的那一段，保留原样；
 * 5. 切完只有 1 段 ⇒ 返回单元素列表，渲染时就是一个气泡。
 *
 * ## 2.382 与 2.36 的差别（复盘用）
 *
 * 2.36 也有这个函数，但渲染用 `Card` 并把名字塞进第一段，导致
 * 「首泡更高、短句被最小高度撑成大空泡」。2.382 把名字移到气泡组外面、
 * 气泡改成 `Box + 显式内边距 + 按内容收缩`（见 `ChatScreen.AssistantBubbles`），
 * **分割规则本身没有变**。
 *
 * ## 已知边界（别当 bug 报）
 *
 *  * 只按换行拆：模型没有换行的长回答仍是一个气泡；
 *  * 行首的列表符号（`- `、`1. `）保留 —— 拆气泡不改文案；
 *  * 流式输出时结尾可能正好是换行：那个空段会被丢弃，下一段到来时自然接上。
 */
fun splitForBubbles(text: String): List<String> {
    if (text.isBlank()) return listOf(text)

    // 规则 3：代码块不拆。整条里任何位置出现围栏都算 ——
    // 手表上把要横读的代码切开只会更难读。
    if (text.contains("```")) return listOf(text)

    val segments = text
        .trimEnd('\n', '\r')          // 规则 1：去掉结尾空行（不动正文里的缩进）
        .split('\n')
        .map { it.trimEnd('\r') }     // 兼容 CRLF
        .filter { it.isNotBlank() }   // 规则 2：空段丢弃

    // 规则 4/5：只有一段（或全空）就原样返回，渲染成一个气泡。
    return if (segments.size <= 1) listOf(text) else segments
}